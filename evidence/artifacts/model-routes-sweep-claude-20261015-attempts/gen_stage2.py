#!/usr/bin/env python3
"""Write the Claude-only stage-2 Workflow script (refute-facts / refute-fit :model-routes) from the stage-1 run record,
mirroring sweep.js runLayer's refuter prompts at 8053f14e7 (forRefuters shape; GPT-6 fit lane not run).
usage: gen_stage2.py <work dir> <stage-1 run record json> <repo worktree>"""
import hashlib, json, re, sys
from pathlib import Path

W, record_path, repo = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])
args = json.loads((W / "args.json").read_text(encoding="utf-8"))
layer_input = json.loads((W / "inputs" / "model-routes.json").read_text(encoding="utf-8"))
record = json.loads(record_path.read_text(encoding="utf-8"))

def find(obj, key):
    if isinstance(obj, dict):
        if key in obj:
            return obj[key]
        for value in obj.values():
            hit = find(value, key)
            if hit is not None:
                return hit
    elif isinstance(obj, list):
        for value in obj:
            hit = find(value, key)
            if hit is not None:
                return hit
    return None

cd = find(record, "claude_discover")
if not isinstance(cd, dict) or not isinstance(cd.get("proposed"), list):
    raise SystemExit("stage-1 record has no claude_discover.proposed; the discover worker returned nothing usable")

def slug(u):  # sweep.js slug(): GitHub owner/repo lowercased, else the lowercased text
    text = str(u or "").strip()
    m = re.search(r"github\.com/([^/#?\s]+/[^/#?\s]+)", text, re.I)
    if m:
        return re.sub(r"\.git$", "", m.group(1), flags=re.I).lower()
    b = re.match(r"^([A-Za-z0-9-]+/[A-Za-z0-9._-]+?)(?:\.git)?/?$", text)
    return b.group(1).lower() if b else text.lower()

carried = layer_input["carried_candidates"]
by_identity = {c["route_identity"].lower(): c for c in carried}
by_id = {c["id"]: c for c in carried}
kept, seen, matched = [], {}, {}
for p in cd["proposed"]:
    key = slug(p.get("repository"))
    if not key or key in seen:
        continue
    carried_hit = by_identity.get(str(p.get("repository", "")).strip().lower())
    if carried_hit is None:
        frag = str(p.get("repository", "")).rsplit("#", 1)[-1].strip().lower()
        carried_hit = by_id.get(frag)
    row = dict(p, families=["claude"])
    if carried_hit is not None:
        row["carried_id"] = carried_hit["id"]
        matched[carried_hit["id"]] = True
    seen[key] = True
    kept.append(row)
label_for = {"REJECTED": "not_adopted"}
added = []
for c in carried:
    if c["id"] in matched:
        continue
    added.append(c["id"])
    kept.append({
        "repository": c["route_identity"], "carried_id": c["id"], "families": ["claude"],
        "proposed_label": label_for.get(c.get("verdict"), "keep_but_compare"),
        "demonstrated_gap": ("CARRIED, NOT LABELLED BY DISCOVERY: prior angle verdict " + str(c.get("verdict"))
                             + "; adoption " + str(c.get("adoption_status")) + "; measure_next: " + str(c.get("measure_next"))),
        "comparison_that_would_overturn": str(c.get("measure_next") or ""),
        "evidence": [{"url": c["doc_url"], "shows": "the carried route's vendor documentation (angle record)"}],
        "upstream_now": None,
        "source": "carried angle record catalogs/landscape/angles/foundation-model-routes.json at 8053f14e7",
    })

def for_refuters(rows):
    return [{"repository": p.get("repository"), "proposed_label": p.get("proposed_label"),
             "demonstrated_gap": p.get("demonstrated_gap"),
             "comparison_that_would_overturn": p.get("comparison_that_would_overturn"),
             "evidence": p.get("evidence"), "upstream_now": p.get("upstream_now"), "proposed_by": p.get("families")}
            for p in rows]

props = json.dumps(for_refuters(kept), indent=1, ensure_ascii=False)
merged_out = W / "stage2-merged.json"
merged_out.write_text(json.dumps({"kept": kept, "carried_added_unlabelled": added,
                                  "discover_proposed_count": len(cd["proposed"])}, indent=1, ensure_ascii=False) + "\n",
                      encoding="utf-8")
src = (repo / "tools/sota-convergence/landscape-sweep/sweep.js").read_text(encoding="utf-8").splitlines()
pages = next(line for line in src if line.startswith("const PAGES = "))
github = next(line for line in src if line.startswith("const GITHUB = "))
body = r"""export const meta = {
  name: 'model-routes-claude-refute',
  description: 'Claude-family half of the model-routes initial sweep, stage 2 of 3: refute-facts and refute-fit :model-routes (Opus 5.5 max)',
  phases: [{ title: 'Refute', detail: 'refute-facts:model-routes and refute-fit:model-routes (Opus max, landscape-sweep-worker)' }],
}
// Generated by gen_stage2.py from the stage-1 run record. Prompts are sweep.js runLayer's refuter prompts verbatim; the
// proposals are the Claude discovery's list plus any carried candidate discovery left unlabelled (CC ruling 19:52Z (A):
// three votes on the 14 carried candidates), with no MAX_PROPOSALS cut. The GPT-6 fit lane is not run.
const A = __ARGS__
const T = A.T
const S = A.S
const WORKER = 'landscape-sweep-worker'
__PAGES__
__GITHUB__
const PROPS = __PROPS__
function fill(template, values) {
  return template.replace(/<<([A-Z_]+)>>/g, (m, k) => (Object.prototype.hasOwnProperty.call(values, k) ? String(values[k]) : m))
}
function inputPath(lid) { return `${S}/inputs/${lid}.json` }
const L = A.layers[0]
phase('Refute')
const [facts, fitC] = await parallel([
  () => agent(T.common + '\n\n' + fill(T.facts, { LAYER_ID: L.layer_id, REQUIREMENT: `see ${inputPath(L.layer_id)} (Read tool)`, PROPOSALS: PROPS }) + `\nFor GitHub facts, ${GITHUB}; ${PAGES}.`,
    { label: `refute-facts:${L.layer_id}`, phase: 'Refute', model: 'opus', effort: 'max', agentType: WORKER, schema: A.schemas.votes }),
  () => agent(T.common + '\n\n' + fill(T.fit, { LAYER_INPUT: `Read the layer input JSON file with the Read tool: ${inputPath(L.layer_id)}`, PROPOSALS: PROPS, LAYER_ID: L.layer_id }) + `\nFor GitHub facts, ${GITHUB}; ${PAGES}.`,
    { label: `refute-fit:${L.layer_id}`, phase: 'Refute', model: 'opus', effort: 'max', agentType: WORKER, schema: A.schemas.votes }),
])
return { sweep: A.sweep_id, stage: 'refute', layer_id: L.layer_id, catalog: L.catalog, facts, fit_claude: fitC }
"""
script = (body.replace("__ARGS__", json.dumps(args, ensure_ascii=False))
              .replace("__PAGES__", pages).replace("__GITHUB__", github)
              .replace("__PROPS__", json.dumps(props, ensure_ascii=False)))
out = W / "claude-stage2-refute.embedded.js"
out.write_text(script, encoding="utf-8")
print("proposals", len(kept), "carried matched", len(matched), "carried added unlabelled", len(added),
      "| merged", hashlib.sha256(merged_out.read_bytes()).hexdigest()[:16],
      "| script", out, hashlib.sha256(out.read_bytes()).hexdigest())
