#!/usr/bin/env python3
"""Write the Claude-only stage-1 Workflow script (discover:model-routes) with the staged args embedded, mirroring
sweep.js claudeDiscoverPrompt at 8053f14e7 (stars null -> STARS_NOTE ''). usage: gen_stage1.py <work dir>"""
import hashlib, json, sys
from pathlib import Path
W = Path(sys.argv[1])
args = json.loads((W / "args.json").read_text(encoding="utf-8"))
assert args["stars"] is None and len(args["layers"]) == 1 and args["layers"][0]["layer_id"] == "model-routes"
body = r"""export const meta = {
  name: 'model-routes-claude-discover',
  description: 'Claude-family half of the model-routes initial sweep, stage 1 of 3: discover:model-routes (Opus 5.5 max, landscape-sweep-worker)',
  phases: [{ title: 'Discover', detail: 'discover:model-routes (Opus max, landscape-sweep-worker)' }],
}
// Generated by gen_stage1.py from the staged args.json (build_args.py at 8053f14e7). The prompt is sweep.js's
// claudeDiscoverPrompt verbatim with A.stars null; the GPT-6 lane is not run (CC ruling 2026-10-15T19:52Z (A)).
const A = __ARGS__
const T = A.T
const S = A.S
const WORKER = 'landscape-sweep-worker'
function fill(template, values) {
  return template.replace(/<<([A-Z_]+)>>/g, (m, k) => (Object.prototype.hasOwnProperty.call(values, k) ? String(values[k]) : m))
}
function inputPath(lid) { return `${S}/inputs/${lid}.json` }
const L = A.layers[0]
phase('Discover')
const prompt = T.common + '\n\n' + fill(T.discover, { LAYER_INPUT: `Read the layer input JSON file with the Read tool: ${inputPath(L.layer_id)}`, STARS_NOTE: '', LAYER_ID: L.layer_id })
const cd = await agent(prompt, { label: `discover:${L.layer_id}`, phase: 'Discover', model: 'opus', effort: 'max', agentType: WORKER, schema: A.schemas.discover })
return { sweep: A.sweep_id, stage: 'discover', layer_id: L.layer_id, catalog: L.catalog, claude_discover: cd }
"""
out = W / "claude-stage1-discover.embedded.js"
out.write_text(body.replace("__ARGS__", json.dumps(args, ensure_ascii=False)), encoding="utf-8")
print(out, hashlib.sha256(out.read_bytes()).hexdigest(), out.stat().st_size)
