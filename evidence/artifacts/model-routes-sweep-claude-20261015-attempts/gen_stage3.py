#!/usr/bin/env python3
"""Write the Claude-only stage-3 Workflow script (critic) from the stage-2 merged list and the stage-2 run record,
mirroring sweep.js's critic summary and prompt at 8053f14e7 (gpt6 fields: not run in this single-family half).
usage: gen_stage3.py <work dir> <stage-2 run record json>"""
import hashlib, json, sys
from pathlib import Path

W, record_path = Path(sys.argv[1]), Path(sys.argv[2])
args = json.loads((W / "args.json").read_text(encoding="utf-8"))
merged = json.loads((W / "stage2-merged.json").read_text(encoding="utf-8"))["kept"]
record = json.loads(record_path.read_text(encoding="utf-8"))

def find(obj, key):
    if isinstance(obj, dict):
        if key in obj:
            return obj[key]
        for value in obj.values():
            hit = find(value, key)
            if hit is not None:
                return hit
    elif isinstance(obj, list):
        for value in obj:
            hit = find(value, key)
            if hit is not None:
                return hit
    return None

facts, fit = find(record, "facts"), find(record, "fit_claude")
refuted = lambda r: [v.get("repository") for v in ((r or {}).get("votes") or []) if v.get("refuted")]
L = args["layers"][0]
summary = [{"layer_id": L["layer_id"], "catalog": L["catalog"], "lost": False,
            "proposed": [f"{p['repository']} [{p.get('proposed_label')}; by {'+'.join(p.get('families') or [])}]" for p in merged],
            "facts_refuted": refuted(facts), "fit_refuted_claude": refuted(fit), "fit_refuted_gpt6": [],
            "gpt6_discover_status": "not_run_single_family_claude_half"}]
(W / "stage3-summary.json").write_text(json.dumps(summary, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
body = r"""export const meta = {
  name: 'model-routes-claude-critic',
  description: 'Claude-family half of the model-routes initial sweep, stage 3 of 3: completeness critic (Opus 5.5 max)',
  phases: [{ title: 'Critic', detail: 'critic (Opus max, landscape-sweep-worker)' }],
}
// Generated by gen_stage3.py. sweep.js's critic prompt verbatim over the one-layer summary; GPT-6 fields are empty
// because this is the single-family Claude half (CC ruling 2026-10-15T19:52Z (A)).
const A = __ARGS__
const T = A.T
const S = A.S
const WORKER = 'landscape-sweep-worker'
const SUMMARY = __SUMMARY__
function fill(template, values) {
  return template.replace(/<<([A-Z_]+)>>/g, (m, k) => (Object.prototype.hasOwnProperty.call(values, k) ? String(values[k]) : m))
}
phase('Critic')
const critic = await agent(T.common + '\n\n' + fill(T.critic, { SUMMARY: `Layer inputs are files ${S}/inputs/<layer_id>.json (Read tool). Summary JSON:\n` + JSON.stringify(SUMMARY, null, 1) }),
  { label: 'critic', phase: 'Critic', model: 'opus', effort: 'max', agentType: WORKER, schema: A.schemas.critic })
return { sweep: A.sweep_id, stage: 'critic', critic }
"""
script = body.replace("__ARGS__", json.dumps(args, ensure_ascii=False)).replace("__SUMMARY__", json.dumps(summary, ensure_ascii=False))
out = W / "claude-stage3-critic.embedded.js"
out.write_text(script, encoding="utf-8")
print("facts refuted", len(refuted(facts)), "fit refuted", len(refuted(fit)), "of", len(merged),
      "| script", out, hashlib.sha256(out.read_bytes()).hexdigest())
